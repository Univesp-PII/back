CREATE TABLE IF NOT EXISTS porteiros (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS moradores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(160) NOT NULL,
  bloco VARCHAR(80) NOT NULL,
  apartamento VARCHAR(40) NOT NULL,
  telefone VARCHAR(40) NOT NULL DEFAULT '',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS encomendas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  morador_id BIGINT REFERENCES moradores(id) ON DELETE SET NULL,
  codigo VARCHAR(120) NOT NULL DEFAULT '',
  empresa VARCHAR(160) NOT NULL DEFAULT '',
  entregador VARCHAR(160) NOT NULL DEFAULT '',
  nome_morador VARCHAR(160) NOT NULL DEFAULT '',
  bloco_morador VARCHAR(80) NOT NULL DEFAULT '',
  apartamento VARCHAR(40) NOT NULL DEFAULT '',
  status VARCHAR(30) NOT NULL DEFAULT 'pendente',
  data_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  data_retirada TIMESTAMPTZ,
  porteiro_registro VARCHAR(160) NOT NULL DEFAULT '',
  porteiro_retirada VARCHAR(160) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS historico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cod VARCHAR(120) NOT NULL DEFAULT '',
  empresa VARCHAR(160) NOT NULL DEFAULT '',
  entregador VARCHAR(160) NOT NULL DEFAULT '',
  morador_nome VARCHAR(160) NOT NULL DEFAULT '',
  porteiro_nome VARCHAR(160) NOT NULL DEFAULT '',
  retirada_porteiro_nome VARCHAR(160) NOT NULL DEFAULT '',
  porteiro_retirada VARCHAR(160) NOT NULL DEFAULT '',
  status VARCHAR(30) NOT NULL DEFAULT 'pendente',
  data_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  data_retirada TIMESTAMPTZ
);